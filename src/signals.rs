//! EE+ (Elephant Edge) strategy signals and position intents.
//!
//! [`StrategySignal`] carries the side, kind, referenced levels, and confidence
//! of an Elephant Edge signal and converts into the canonical kernel [`Signal`];
//! [`PositionIntent`] is the validated "what to trade" context downstream
//! planners and adapters consume. Zero-I/O, `Decimal`-only, WASM-clean.

use chrono::{DateTime, Utc};
use rust_decimal::Decimal;
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

use crate::error::CoreError;
use crate::levels::LevelId;
use crate::order::OrderSide;
use crate::signal::{Signal, SignalDirection, SignalHorizon, Timeframe};
use crate::types::{InstrumentId, Money, Quantity};

/// The `generated_by` tag stamped on [`StrategySignal`]-derived [`Signal`]s.
pub const ELEPHANT_EDGE_SIGNAL_GENERATOR: &str = "elephant_edge";

/// Kind of EE+ strategy signal.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum SignalKind {
    /// Price breaking out of a level band.
    Breakout,
    /// Price reversing at a level.
    Reversal,
    /// Price retesting a broken level.
    Retest,
}

/// An EE+ strategy signal anchored to one or more levels on the level map.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct StrategySignal {
    /// Intended trade side.
    pub side: OrderSide,
    /// Signal kind.
    pub kind: SignalKind,
    /// Levels this signal is anchored to (non-empty).
    pub ref_levels: Vec<LevelId>,
    /// Confidence in `0..=100`.
    pub confidence: Decimal,
    /// The instrument the signal is about.
    pub instrument: InstrumentId,
    /// When the signal was generated (injected — zero wall clock).
    pub timestamp: DateTime<Utc>,
}

impl StrategySignal {
    /// Validated constructor.
    ///
    /// # Errors
    /// Returns [`CoreError::Validation`] when `ref_levels` is empty or
    /// `confidence` is outside `0..=100`.
    pub fn new(
        side: OrderSide,
        kind: SignalKind,
        ref_levels: Vec<LevelId>,
        confidence: Decimal,
        instrument: InstrumentId,
        timestamp: DateTime<Utc>,
    ) -> Result<Self, CoreError> {
        if ref_levels.is_empty() {
            return Err(CoreError::Validation(
                "strategy signal must reference at least one level".to_string(),
            ));
        }
        if !(Decimal::ZERO..=Decimal::from(100)).contains(&confidence) {
            return Err(CoreError::Validation(format!(
                "signal confidence must be in 0..=100: {confidence}"
            )));
        }
        Ok(Self {
            side,
            kind,
            ref_levels,
            confidence,
            instrument,
            timestamp,
        })
    }
}

/// Convert an EE+ signal into the canonical kernel [`Signal`].
///
/// Maps `Buy` → [`SignalDirection::Bullish`], `Sell` →
/// [`SignalDirection::Bearish`], strength = `confidence / 100`, horizon
/// [`SignalHorizon::Intraday`], timeframe [`Timeframe::M1`], generated by
/// `"elephant_edge"`, with entry/stop/take-profit levels unset.
impl From<StrategySignal> for Signal {
    fn from(signal: StrategySignal) -> Self {
        let direction = match signal.side {
            OrderSide::Buy => SignalDirection::Bullish,
            OrderSide::Sell => SignalDirection::Bearish,
        };
        Signal::new(
            signal.instrument,
            direction,
            SignalHorizon::Intraday,
            Timeframe::M1,
            signal.confidence / Decimal::from(100),
            ELEPHANT_EDGE_SIGNAL_GENERATOR,
            signal.timestamp,
        )
    }
}

/// A validated intent to open or adjust a position.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
pub struct PositionIntent {
    /// The instrument.
    pub instrument: InstrumentId,
    /// Intended side.
    pub side: OrderSide,
    /// Intended quantity (strictly positive).
    pub quantity: Quantity,
    /// Maximum capital at risk.
    pub risk_cap: Money,
    /// Maximum fraction of available capital to deploy, in `0..=1`.
    pub max_fraction: Decimal,
}

impl PositionIntent {
    /// Validated constructor.
    ///
    /// # Errors
    /// Returns [`CoreError::Validation`] when `quantity` is not strictly
    /// positive or `max_fraction` is outside `0..=1`.
    pub fn new(
        instrument: InstrumentId,
        side: OrderSide,
        quantity: Quantity,
        risk_cap: Money,
        max_fraction: Decimal,
    ) -> Result<Self, CoreError> {
        if !quantity.is_positive() {
            return Err(CoreError::Validation(
                "position quantity must be strictly positive".to_string(),
            ));
        }
        if !(Decimal::ZERO..=Decimal::ONE).contains(&max_fraction) {
            return Err(CoreError::Validation(format!(
                "position max_fraction must be in 0..=1: {max_fraction}"
            )));
        }
        Ok(Self {
            instrument,
            side,
            quantity,
            risk_cap,
            max_fraction,
        })
    }
}
